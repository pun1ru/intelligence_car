/*
 * 导航路径表（改这里，只改这里）
 *
 * 怎么填：锥桶布局公布后，在场地量出每个要穿过的"间隙中点"相对发车点的
 * 前后距离 X 和左右偏移 Y，按通过顺序写进下面的表。
 *   - 原点 = 进入导航状态时车的位置，车头方向 = 0 度，+X 向前、+Y 向左；
 *   - 第一个点建议放在车正前方 0.3~0.5 m，让车先走直线再进桶；
 *   - 最后一个点放回发车线附近，pure_pursuit 用 goal_radius_m 判断"跑完"；
 *   - 点越密贴线越紧，但太密会让前视点频繁跳变，间隔 0.3~0.6 m 比较合适。
 *
 * 填好后把 APP_NAV_PATH_DEFINED 改成 1。没有填之前 count 返回 0，
 * 调用方必须把"没有路径"当作不可行驶处理。
 */
/* 当前表里是**测试路径（曲率连续的 180° 掉头）**：
 *   直行 1.0 m → 15° 缓入（回旋线）→ 半径 0.4 m 圆弧 150°
 *   → 15° 缓出 → 直行 1.0 m。
 * 尺寸：缓入/缓出各 0.209 m，圆弧 1.047 m，总里程 3.466 m；终点 (0, -0.809)，
 * 停住时车头朝 -X（相对发车方向转 180°）。掉头过程中车头最远伸出到 x≈1.50 m，
 * 所以场地要留约 1.55 m（前后）× 0.85 m（左右）。
 *
 * 为什么要缓入缓出：路径曲率如果从 0 突变到 1/0.4，转向环来不及把方向打到位，
 * 实测进弯切内圈（cross 约 -5 cm）、出弯甩外圈（+12 cm）。回旋线让曲率在
 * 0.209 m（0.2 m/s 下约 1 s）里线性长到 1/0.4、再线性退回 0，给转向环留出
 * 反应时间。最大曲率不变，最小转弯半径仍是 0.4 m。
 *
 * 点间距 0.078 m（折线偏离真曲线约 2 mm）：前视距离必须 ≥ 2 倍点间距，否则
 * 前视点在点之间跳变、车会发抖。见 general_define.h 的
 * NAV_TRACKING_LOOKAHEAD_M（当前 0.18）。直线段方向不变，点可以稀一些。
 *
 * **比赛前必须用实测锥桶间隙坐标整体替换**，否则车会照着这条假路径走。 */
#define APP_NAV_PATH_DEFINED 1

