#include "app_nav_path.h"

#include <stddef.h>

/*
 * 导航路径表（改这里，只改这里）
 *
 * 怎么填：锥桶布局公布后，在场地量出每个要穿过的"间隙中点"相对发车点的
 * 前后距离 X 和左右偏移 Y，按通过顺序写进下面的表。
 *   - 原点 = 进入导航状态时车的位置，车头方向 = 0 度，+X 向前、+Y 向左；
 *   - 第一个点建议放在车正前方 0.3~0.5 m，让车先走直线再进桶；
 *   - 最后一个点放回发车线附近，pure_pursuit 用 goal_radius_m 判断"跑完"；
 *   - 点越密贴线越紧，但太密会让前视点频繁跳变，间隔 0.3~0.6 m 比较合适。
 *
 * 填好后把 APP_NAV_PATH_DEFINED 改成 1。没有填之前 count 返回 0，
 * 调用方必须把"没有路径"当作不可行驶处理。
 */
/* 当前表里是**测试路径**：直行 0.5 m + 半径 0.4 m 右转 90° + 出弧直行 0.4 m，
 * 用来验证导航层：直行看速度环、持续转弯看转向环、最后一点看终点判定。
 * 几何：圆心在 (0.5, -0.4)，弧长 0.4*pi/2≈0.63 m；出弧后沿车头方向（-Y）再走
 * 0.4 m，终点 (0.9, -0.8)。
 *
 * 为什么出弧后要留一段直线：终点判定半径是 0.10 m，落在"弧"上时提前停车会
 * 少转一个角度（0.10/0.40 弧度 ≈14°），而落在"直线上"时早停晚停都不改变朝向
 * 要求，所以"停住时车头该朝哪"变成干净读数。另外这段直线还能顺便看到横向偏差
 * 被拉回路径的快慢。
 *
 * 弧上取 8 段（每段 11.25°，点间距 0.078 m）：折线偏离真圆弧只有约 2 mm，
 * 也让"前视距离"可以取得更小——前视距离必须 ≥ 2 倍点间距，否则前视点会在点
 * 之间跳变，车会发抖。直线段则不必加密（方向处处相同）。见 general_define.h
 * 的 NAV_TRACKING_LOOKAHEAD_M。
 *
 * **比赛前必须用实测锥桶间隙坐标整体替换**，否则车会照着这条假路径走。 */
#define APP_NAV_PATH_DEFINED 1

static const pure_pursuit_point_t nav_path_points[] =
{
    {0.25f,  0.00f},   /* 直行段方向（近点，起步更稳） */
    {0.50f,  0.00f},   /* 直线结束、弧的起点 */
    {0.578f, -0.008f}, /* 已转 11.25° */
    {0.653f, -0.030f}, /* 已转 22.5° */
    {0.722f, -0.067f}, /* 已转 33.75° */
    {0.783f, -0.117f}, /* 已转 45° */
    {0.833f, -0.178f}, /* 已转 56.25° */
    {0.870f, -0.247f}, /* 已转 67.5° */
    {0.892f, -0.322f}, /* 已转 78.75° */
    {0.900f, -0.400f}, /* 已转 90°，车头朝右（-Y） */
    {0.900f, -0.800f}  /* 出弧直行 0.4 m = 终点：到点后目标速度归零，原地停住 */
};

/*
 * 填写示例（把上面的数组整体替换成这种形式，然后把宏改成 1）：
 *
 *   static const pure_pursuit_point_t nav_path_points[] =
 *   {
 *       {0.40f,  0.00f},   // 发车后先直行 0.4 m
 *       {1.10f, -0.35f},   // 第 1 个锥桶间隙（偏右）
 *       {1.80f,  0.30f},   // 第 2 个锥桶间隙（偏左）
 *       {2.50f, -0.25f},   // 第 3 个锥桶间隙
 *       {0.20f,  0.00f},   // 回到发车线附近
 *   };
 */

uint16_t app_nav_path_count(void)
{
#if (APP_NAV_PATH_DEFINED != 0)
    return (uint16_t)(sizeof(nav_path_points) / sizeof(nav_path_points[0]));
#else
    return 0U;
#endif
}

const pure_pursuit_point_t *app_nav_path_points(void)
{
    return nav_path_points;
}
